/*
 * Builds src/site/design.css from design/main.css (the designer's stylesheet, kept unchanged).
 *
 * Every rule is scoped so it only applies to the redesigned website:
 *   - normal selectors get the `.rg` prefix (the wrapper div in src/site/SiteLayout.js)
 *   - `html` and `body` rules apply only while the layout has added `rg-html` / `rg-body` to them
 *   - `:root` design tokens go on `html.rg-html` (so body inherits them) and on `.rg`
 * This keeps the design from leaking into /resolutesports, the privacy notice and the admin panel,
 * which have their own styles.
 *
 * Run after changing design/main.css:  node scripts/scope-design-css.js
 */
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const SRC = path.join(__dirname, '..', 'design', 'main.css');
const OUT = path.join(__dirname, '..', 'src', 'site', 'design.css');

function scope(selector) {
  const s = selector.trim();
  if (s === ':root') return ['html.rg-html', '.rg'];
  if (/^html\b/.test(s)) return [s.replace(/^html/, 'html.rg-html')];
  if (/^body\b/.test(s)) return [s.replace(/^body/, 'body.rg-body')];
  return [`.rg ${s}`];
}

const root = postcss.parse(fs.readFileSync(SRC, 'utf8'), { from: SRC });
root.walkRules((rule) => {
  if (rule.parent && rule.parent.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.flatMap(scope);
});

const header = '/* GENERATED by scripts/scope-design-css.js from design/main.css. Do not edit by hand. */\n';
fs.writeFileSync(OUT, header + root.toString());
console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
